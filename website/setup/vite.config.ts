import type { Plugin } from 'vite'
import { createHash } from 'node:crypto'
import { readdirSync, readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { defineConfig } from 'vite'

// The provisioning page, a static PWA of its own (served on SETUP_HOST by
// wrangler.setup.jsonc). `bun run build:setup` builds it into ../dist-setup.

const root = fileURLToPath(new URL('.', import.meta.url))
const publicDir = `${root}public`

// The service worker precaches every file of this build, so the page works
// offline once it has been opened. Its cache name changes with the build.
function serviceWorker(): Plugin {
  return {
    name: 'mica-setup-sw',
    apply: 'build',
    generateBundle(_, bundle) {
      const publicFiles = readdirSync(publicDir).filter(f => !f.startsWith('_'))
      const files = ['/', ...Object.keys(bundle).filter(f => f !== 'index.html').map(f => `/${f}`), ...publicFiles.map(f => `/${f}`)].sort()
      const hash = createHash('sha256')
      for (const [name, out] of Object.entries(bundle))
        hash.update(name).update(out.type === 'chunk' ? out.code : out.source)
      for (const f of publicFiles)
        hash.update(f).update(readFileSync(`${publicDir}/${f}`))
      const cache = `mica-setup-${hash.digest('hex').slice(0, 12)}`
      this.emitFile({
        type: 'asset',
        fileName: 'sw.js',
        source: `// Generated by setup/vite.config.ts.
const CACHE = ${JSON.stringify(cache)}
const FILES = ${JSON.stringify(files)}
self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then(c => c.addAll(FILES)).then(() => self.skipWaiting()))
})
self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys()
    .then(keys => Promise.all(keys.filter(k => k !== CACHE).map(k => caches.delete(k))))
    .then(() => self.clients.claim()))
})
self.addEventListener('fetch', (e) => {
  const r = e.request
  if (r.method !== 'GET' || new URL(r.url).origin !== location.origin)
    return
  e.respondWith(caches.match(r.mode === 'navigate' ? '/' : r, { ignoreSearch: true, ignoreVary: true }).then(hit => hit || fetch(r)))
})
`,
      })
    },
  }
}

export default defineConfig({
  root,
  publicDir,
  plugins: [serviceWorker()],
  build: {
    outDir: fileURLToPath(new URL('../dist-setup', import.meta.url)),
    emptyOutDir: true,
  },
})
